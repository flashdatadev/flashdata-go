func TestSubtitleLanguages(t *testing.T) {
	for _, source := range []Source{SourceYouTubeTranscript, SourceYouTubeCaptions} {
		for _, language := range []any{nil, "en", Ptr("en"), []string{"en"}, []string{"en", "es"}, []string{"a", "b", "c", "d", "e", "f", "g", "h", "i", "j"}} {
			var single *string
			var multiple []string
			switch value := language.(type) {
			case string:
				single = Ptr(value)
			case *string:
				single = value
			case []string:
				multiple = value
			}
			var params any = &YouTubeTranscriptParams{Language: single, Languages: multiple, Auto: Ptr(false)}
			if source == SourceYouTubeCaptions {
				params = &YouTubeCaptionsParams{Language: single, Languages: multiple, Auto: Ptr(false)}
			}
			wire, err := json.Marshal(params)
			if err != nil {
				t.Fatal(err)
			}
			var roundTrip YouTubeTranscriptParams
			if err = json.Unmarshal(wire, &roundTrip); err != nil {
				t.Fatal(err)
			}
			if !reflect.DeepEqual(roundTrip.Languages, multiple) || !reflect.DeepEqual(roundTrip.Language, single) {
				t.Fatal("language round trip changed selection")
			}
			query := Query{Source: source, VideoID: "aircAruvnKk", Params: params}
			for _, async := range []bool{false, true} {
				if err := ValidateQuery(query, async); err != nil {
					t.Fatal(source, language, err)
				}
			}
			if err := ValidateBulkCreate(CreateBulkJobRequest{Source: source, Options: params}); err != nil {
				t.Fatal(err)
			}
			body, _ := json.Marshal(params)
			if language == nil && strings.Contains(string(body), "language") {
				t.Fatal("omitted language was filled")
			}
		}
		for _, language := range []any{"", "en,es", strings.Repeat("a", 36), []string{}, []string{"en", "en"}, []any{"en", nil}, []string{"a", "b", "c", "d", "e", "f", "g", "h", "i", "j", "k"}} {
			params := map[string]any{"language": language}
			if err := ValidateQuery(Query{Source: source, VideoID: "aircAruvnKk", Params: params}, false); err == nil {
				t.Fatalf("accepted invalid language: %#v", language)
			}
			if err := ValidateBulkCreate(CreateBulkJobRequest{Source: source, Options: params}); err == nil {
				t.Fatal("bulk accepted invalid language")
			}
		}
	}
	if err := ValidateQuery(Query{Source: SourceYouTubeSuggestions, Query: "hello", Params: map[string]any{"language": []string{"en", "es"}}}, false); err == nil {
		t.Fatal("suggestions unexpectedly accepts language lists")
	}
}

func TestSubtitlePartialResultsPreserved(t *testing.T) {
	for _, source := range []Source{SourceYouTubeTranscript, SourceYouTubeCaptions} {
		for _, empty := range []bool{false, true} {
			tracks := []any{}
			if !empty {
				tracks = append(tracks, map[string]any{"videoId": "aircAruvnKk", "languageCode": "en", "fullText": "Example", "segments": []any{map[string]any{"start": 1.5, "end": 2, "text": "Example"}}})
			}
			payload := map[string]any{"videoId": "aircAruvnKk", "isAutoGenerated": false, "tracks": tracks, "errors": []any{map[string]any{"languageCode": "es", "code": "language_unavailable", "message": "No Spanish track"}}}
			calls := 0
			c, _ := testClient(t, func(w http.ResponseWriter, r *http.Request) {
				calls++
				var q map[string]any
				_ = json.NewDecoder(r.Body).Decode(&q)
				if !reflect.DeepEqual(q["params"], map[string]any{"language": []any{"en", "es"}, "auto": false}) {
					t.Errorf("changed request: %#v", q)
				}
				respond(w, map[string]any{"source": source, "status": "done", "results": []any{payload}, "usage": map[string]any{"credits": 0.01}})
			})
			response, err := c.Queries.Realtime(context.Background(), Query{Source: source, VideoID: "aircAruvnKk", Params: map[string]any{"language": []string{"en", "es"}, "auto": false}})
			if err != nil {
				t.Fatal(err)
			}
			var result YouTubeTranscriptPayload
			if err = json.Unmarshal(response.Results[0], &result); err != nil {
				t.Fatal(err)
			}
			if calls != 1 || len(result.Tracks) != len(tracks) || len(result.Errors) != 1 || result.Errors[0].Code != "language_unavailable" {
				t.Fatalf("lost partial results: %+v", result)
			}
		}
	}
}

func TestPublicOfflineValidationForCLI(t *testing.T) {
	if len(Sources()) != 15 {
		t.Fatal("missing source")
	}
	for _, source := range Sources() {
		schema, err := QuerySchema(source)
		if err != nil || !json.Valid(schema) {
			t.Fatal(source, err)
		}
	}
	if err := ValidateQuery(Query{Source: SourceGoogleSearch, Query: "hello", Params: map[string]any{"num": 5}}, false); err != nil {
		t.Fatal(err)
	}
	if err := ValidateQuery(Query{Source: SourceGoogleSearch, Query: "hello", Params: map[string]any{"num": 101}}, false); err == nil {
		t.Fatal("invalid query accepted")
	}
	if err := ValidateBulkCreate(CreateBulkJobRequest{Source: SourceYouTubeMetadata}); err != nil {
		t.Fatal(err)
	}
	if err := ValidateBulkCreate(CreateBulkJobRequest{Source: SourceYouTubeDownload}); err == nil {
		t.Fatal("missing download storage")
	}
	if err := ValidateRegistration(RegistrationRequest{Name: "Go CLI", Scopes: []Source{SourceGoogleSearch}}); err != nil {
		t.Fatal(err)
	}
	if err := ValidateRegistration(RegistrationRequest{Name: "", Scopes: []Source{SourceGoogleSearch}}); err == nil {
		t.Fatal("invalid registration accepted")
	}
	if _, err := NormalizeOrigin("http://example.com"); err == nil {
		t.Fatal("unsafe origin")
	}
}

