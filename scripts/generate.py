"""Regenerate public Go wire types from the checked-in API contracts (Python 3.10+)."""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = ROOT / "internal/contract"
SCHEMAS = json.loads((CONTRACT / "schemas.json").read_text(encoding="utf-8"))
OPENAPI = json.loads((CONTRACT / "openapi.json").read_text(encoding="utf-8"))
ACRONYMS = {
    "id": "ID",
    "ids": "IDs",
    "url": "URL",
    "urls": "URLs",
    "api": "API",
    "fps": "FPS",
    "hl": "HL",
    "gl": "GL",
    "tb": "TB",
    "ms": "MS",
    "ndjson": "NDJSON",
    "csrf": "CSRF",
    "ip": "IP",
    "ttl": "TTL",
    "utc": "UTC",
    "youtube": "YouTube",
    "gcs": "GCS",
}


def name(s):
    if s in {"360", "3d", "4k"}:
        return {"360": "Video360", "3d": "ThreeD", "4k": "FourK"}[s]
    words = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s).split("_")
    return "".join(ACRONYMS.get(w.lower(), w[0].upper() + w[1:]) for w in words if w)


def typename(s):
    return {"ApiAccess": "APIAccess", "ApiKeyUsage": "APIKeyUsage"}.get(s, name(s))


models = {}


def gotype(s, hint):
    if "$ref" in s:
        return typename(s["$ref"].rsplit("/", 1)[1])
    t = s.get("type")
    nullable = isinstance(t, list) and "null" in t
    if isinstance(t, list):
        t = next((v for v in t if v != "null"), None)
    union = s.get("oneOf", s.get("anyOf", []))
    if union:
        real = [v for v in union if v.get("type") != "null"]
        if len(real) == 1:
            return "*" + gotype(real[0], hint)
        return "json.RawMessage"
    if t == "string":
        v = "string"
    elif t == "integer":
        v = "int64"
    elif t == "number":
        v = "float64"
    elif t == "boolean":
        v = "bool"
    elif t == "array":
        return "[]" + gotype(s.get("items", {}), hint + "Item")
    elif t == "object" or "properties" in s:
        if not s.get("properties"):
            return "map[string]json.RawMessage"
        models[hint] = s
        v = hint
    else:
        return "json.RawMessage"
    return "*" + v if nullable else v


out = [
    "// Code generated by scripts/generate.py; DO NOT EDIT.",
    "package flashdata",
    'import "encoding/json"',
]
# Request types are separate from source-specific optional parameters.
for source, schema in SCHEMAS.items():
    prefix = name(source)
    props = schema["properties"]
    fields = []
    for field, prop in props.items():
        if field == "source":
            continue
        typ = gotype(prop, prefix + ("Params" if field == "params" else name(field)))
        required = field in schema.get("required", [])
        if (
            not required
            and typ not in ["json.RawMessage"]
            and not typ.startswith(("*", "[]", "map["))
        ):
            typ = "*" + typ
        fields.append(
            f'{name(field)} {typ} `json:"{field}{"" if required else ",omitempty"}"`'
        )
    out += [
        f"// {prefix}Input is the {source} query. See https://flashdata.dev/docs/sources/{source}.",
        f"type {prefix}Input struct {{",
        *fields,
        "}",
        f"func (in {prefix}Input) Request() Query {{",
        f"q := Query{{Source: Source{prefix}}}",
    ]
    for field in props:
        if field == "source":
            continue
        if field == "params" and field not in schema.get("required", []):
            out.append("if in.Params != nil { q.Params = in.Params }")
        else:
            out.append(f"q.{name(field)} = in.{name(field)}")
    out += ["return q", "}"]
# All named response models from the same snapshot used by Python/TypeScript.
for n, s in OPENAPI["components"]["schemas"].items():
    if (
        n
        in json.loads(
            (CONTRACT / "onboarding-contract.json").read_text(encoding="utf-8")
        )["schemas"]
    ):
        continue
    if n.startswith(("Query_", "AsyncQuery_")) or n in (
        "CreateBulkJobRequest",
        "UpdateBulkJobRequest",
    ):
        continue
    if n == "MarkdownQueryResult":
        # The schema permits metadata beyond its three required fields. Include
        # the timestamps/ID used by realtime and stored-result wire envelopes.
        s = {
            **s,
            "properties": {
                **s["properties"],
                **{
                    field: {"type": "string"}
                    for field in ("id", "created_at", "completed_at", "expires_at")
                },
            },
        }
    models[typename(n)] = s
# Provider payload hints are derived from sanitized examples, never a required response shape.
FIXTURES = json.loads(
    (ROOT / "testdata/source-examples.json").read_text(encoding="utf-8")
)


def infer(values):
    values = [v for v in values if v is not None]
    if not values:
        return {}
    kinds = {type(v) for v in values}
    if kinds <= {int, float}:
        return {"type": ["number", "null"]}
    if len(kinds) != 1:
        return {}
    if isinstance(values[0], dict):
        keys = dict.fromkeys(k for v in values for k in v)
        return {
            "type": "object",
            "properties": {k: infer([v[k] for v in values if k in v]) for k in keys},
        }
    if isinstance(values[0], list):
        return {"type": "array", "items": infer([x for v in values for x in v])}
    return {
        "type": [
            {str: "string", bool: "boolean"}.get(type(values[0]), "string"),
            "null",
        ]
    }


for source, fixture in FIXTURES.items():
    payloads = fixture.get("response", {}).get("results", [])
    if payloads:
        models[name(source) + "Payload"] = infer(payloads)
seen = set()
while True:
    pending = [n for n in models if n not in seen]
    if not pending:
        break
    for n in pending:
        seen.add(n)
        s = models[n]
        if s.get("type") != "object" and not s.get("properties"):
            out += [f"type {n} " + gotype(s, n + "Value")]
            continue
        out += [f"// {n} is a management or data API response.", f"type {n} struct {{"]
        for field, p in s.get("properties", {}).items():
            typ = gotype(p, n + name(field))
            required = field in s.get("required", [])
            # Keep the published Go model's JSON marshaling behavior while the
            # newer API schema makes these response fields explicitly required.
            if n == "DataQueryResponse" and field in ("source", "status", "results"):
                required = False
            request_model = any(
                n.startswith(name(source) + "Params") for source in SCHEMAS
            )
            if (
                request_model
                and not required
                and not typ.startswith(("*", "[]", "map["))
                and typ != "json.RawMessage"
            ):
                typ = "*" + typ
            out.append(
                f'{name(field)} {typ} `json:"{field}{"" if required else ",omitempty"}"`'
            )
        out.append("}")
(ROOT / "types_generated.go").write_text("\n".join(out) + "\n", encoding="utf-8")
# Typed source helpers keep synchronous and submitted return types distinct.
helpers = [
    "// Code generated by scripts/generate.py; DO NOT EDIT.",
    "package flashdata",
    'import "context"',
]
for source in SCHEMAS:
    prefix = name(source)
    group = "Google" if source.startswith("google_") else "YouTube"
    method = name(source.split("_", 1)[1])
    method = {"Trainability": "LicenseCheck"}.get(method, method)
    if source != "youtube_download":
        helpers += [
            f"// {method} runs {source} in realtime.",
            f"func (r *{group}Service) {method}(ctx context.Context, input {prefix}Input) (*DataQueryResponse, error) {{",
            "return r.c.Queries.Realtime(ctx, input.Request())",
            "}",
            f"// {method}WithFormat runs {source} with JSON, text or Markdown response headers.",
            f"func (r *{group}Service) {method}WithFormat(ctx context.Context, input {prefix}Input, options ContentOptions) (*FormattedResponse, error) {{",
            "return r.c.Queries.RealtimeWithFormat(ctx, input.Request(), options)",
            "}",
        ]
    asyncname = method if source == "youtube_download" else method + "Async"
    helpers += [
        f"// {asyncname} submits {source}. Save the returned job ID before polling.",
        f"func (r *{group}Service) {asyncname}(ctx context.Context, input {prefix}Input, callbackURL string) (*AsyncSubmission, error) {{",
        "q := input.Request(); q.CallbackURL = callbackURL",
        "return r.c.Queries.Submit(ctx, q)",
        "}",
        f"// {asyncname}WithFormat submits {source} with a JSON or plain-text receipt.",
        f"func (r *{group}Service) {asyncname}WithFormat(ctx context.Context, input {prefix}Input, callbackURL string, options ResponseOptions) (*FormattedResponse, error) {{",
        "q := input.Request(); q.CallbackURL = callbackURL",
        "return r.c.Queries.SubmitWithFormat(ctx, q, options)",
        "}",
    ]
(ROOT / "sources_generated.go").write_text("\n".join(helpers) + "\n")
print(
    f"Generated {len(SCHEMAS)} source inputs and {len(seen)} response/parameter types."
)
